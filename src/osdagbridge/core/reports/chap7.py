def _fig_block(fig_paths, attr, caption, label, width):
    """Return a figure environment for attr if the chart PNG exists."""
    if not fig_paths or attr not in fig_paths:
        return ""
    path = str(fig_paths[attr]).replace('\\', '/')
    return ("\\begin{figure}[H]\n\\centering\n"
            "\\includegraphics[width=" + width + "\\textwidth]{" + path + "}\n"
            "\\caption{\\textbf{" + caption + "}}\n"
            "\\label{" + label + "}\n\\end{figure}")
